import { randomUUID } from "node:crypto";

function createUserMessage(input) {
	return Object.freeze({
		...input,
		role: "user",
		id: randomUUID()
	});
}

export function apply(ctx) {
	if (ctx.tools && typeof ctx.tools.register === "function") {
		ctx.tools.register({
			name: "genui_html",
			description: "Render a complete purpose-built interactive UI generated by YOU as one self-contained HTML document. Supply full HTML with inline CSS and JavaScript. The document runs in a sandboxed iframe without same-origin, forms, popups, downloads, parent access, or network permissions. Use native browser APIs only; include all data in the document. To send interactive data or actions back to the conversation, the script inside the iframe can call window.parent.postMessage({ type: 'genui:submit', payload: ... }, '*').",
			parameters: {
				type: "object",
				additionalProperties: false,
				required: ["html"],
				properties: {
					html: {
						type: "string",
						description: "Complete self-contained HTML document with inline CSS and JavaScript."
					},
					title: {
						type: "string",
						description: "Optional concise title for the generated interface card."
					},
					height: {
						type: "number",
						description: "Requested inline frame height in pixels, 180-720 (defaults to 420)."
					}
				}
			},
			output: {
				schema: {
					type: "object",
					additionalProperties: false,
					properties: {
						html: { type: "string" },
						title: { type: "string" },
						height: { type: "number" }
					}
				},
				render(_args, value) {
					const titleText = String((value && value.title) || "Generated interface");
					return [{
						type: "text",
						text: `[Generative UI: ${titleText}]`
					}];
				},
				presentationMeta(_args, value) {
					return {
						html: String((value && value.html) || ""),
						title: String((value && value.title) || "Generated interface"),
						height: Number((value && value.height) || 420)
					};
				}
			},
			async execute(args) {
				const rawHtml = String(args.html || "");
				if (!rawHtml.trim()) throw new Error("html parameter must be non-empty");
				if (rawHtml.length > 256000) throw new Error("Generated HTML exceeds maximum size limit (250 KB)");

				const title = String(args.title || "Generated interface").trim().slice(0, 120);
				const heightNum = Number(args.height);
				const height = Number.isFinite(heightNum)
					? Math.max(180, Math.min(Math.round(heightNum), 720))
					: 420;

				return {
					html: rawHtml,
					title: title || "Generated interface",
					height
				};
			}
		});
	}

	if (ctx.commands && typeof ctx.commands.register === "function") {
		ctx.commands.register({
			name: "genui",
			description: "Instruct the agent to generate an inline interactive UI for a specific request",
			input: {
				hint: "<describe the interface to generate>",
				images: false
			},
			handler(invocation) {
				const raw = (invocation.rawInput || "").trim();
				if (!raw) {
					return {
						kind: "error",
						text: "Usage: /genui <describe the interface you want generated>\nExample: /genui an interactive financial loan repayment calculator with amortization chart"
					};
				}
				if (invocation.agent && typeof invocation.agent.followup === "function") {
					invocation.agent.followup(createUserMessage({
						content: [{
							type: "text",
							text: `Please generate a purpose-built interactive inline UI using the genui_html tool for the following request:\n${raw}`
						}],
						source: { kind: "user" }
					}));
				}
				return {
					kind: "success",
					text: `Generative UI request submitted: "${raw}". Generating custom interface...`
				};
			}
		});
	}
}

export const inject = ["tools", "commands"];
